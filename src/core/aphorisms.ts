export function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

/** 按地址确定性选取：同一页永远得到同一句 */
export function pickByAddress<T>(arr: T[], address: bigint): T {
  return arr[Number(address % BigInt(arr.length))];
}
